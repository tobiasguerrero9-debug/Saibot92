export const SESSION_TRANSITIONS = Object.freeze({
  IDLE: ['CONFIGURED', 'EMERGENCY_STOPPED'],
  CONFIGURED: ['CONFIGURED', 'ARMED', 'EMERGENCY_STOPPED'],
  ARMED: ['OBSERVING', 'EMERGENCY_STOPPED', 'ERROR'],
  OBSERVING: ['ENTRY_ELIGIBLE', 'PAUSED', 'EMERGENCY_STOPPED', 'ERROR'],
  ENTRY_ELIGIBLE: ['PLACING_ORDER', 'OBSERVING', 'EMERGENCY_STOPPED', 'ERROR'],
  PLACING_ORDER: ['ORDER_OPEN', 'POSITION_OPEN', 'COMPLETED', 'EMERGENCY_STOPPED', 'ERROR'],
  ORDER_OPEN: ['POSITION_OPEN', 'COMPLETED', 'EMERGENCY_STOPPED', 'ERROR'],
  POSITION_OPEN: ['MANAGING', 'EXITING', 'EMERGENCY_STOPPED', 'ERROR'],
  MANAGING: ['EXITING', 'COMPLETED', 'EMERGENCY_STOPPED', 'ERROR'],
  EXITING: ['COMPLETED', 'EMERGENCY_STOPPED', 'ERROR'],
  COMPLETED: ['CONFIGURED', 'EMERGENCY_STOPPED'],
  PAUSED: ['OBSERVING', 'EMERGENCY_STOPPED', 'ERROR'],
  ERROR: ['EMERGENCY_STOPPED', 'CONFIGURED'],
  EMERGENCY_STOPPED: ['CONFIGURED', 'EXITING', 'COMPLETED'],
});
export function sessionTransition(from, to) {
  if (!SESSION_TRANSITIONS[from]?.includes(to)) throw new Error(`Invalid execution session transition ${from} -> ${to}`);
  return to;
}
