const transitions = {
  LOCKED: ['DISCONNECTED'], DISCONNECTED: ['OBSERVING', 'LOCKED', 'ERROR'],
  OBSERVING: ['ANALYZING', 'MANAGING', 'POSITION_OPEN', 'LOCKED', 'DISCONNECTED', 'ERROR'],
  ANALYZING: ['PROPOSAL_READY', 'RISK_BLOCKED', 'ERROR', 'LOCKED', 'DISCONNECTED'],
  PROPOSAL_READY: ['AWAITING_APPROVAL', 'OBSERVING', 'LOCKED', 'DISCONNECTED'],
  AWAITING_APPROVAL: ['EXECUTING', 'OBSERVING', 'RISK_BLOCKED', 'LOCKED', 'DISCONNECTED', 'ERROR'],
  EXECUTING: ['POSITION_OPEN', 'OBSERVING', 'RISK_BLOCKED', 'ERROR', 'LOCKED', 'DISCONNECTED'],
  POSITION_OPEN: ['MANAGING', 'EXITED', 'LOCKED', 'DISCONNECTED', 'ERROR'],
  MANAGING: ['POSITION_OPEN', 'EXITED', 'ERROR', 'LOCKED', 'DISCONNECTED'],
  EXITED: ['OBSERVING', 'LOCKED', 'DISCONNECTED'], RISK_BLOCKED: ['OBSERVING', 'ANALYZING', 'LOCKED', 'DISCONNECTED'],
  ERROR: ['OBSERVING', 'DISCONNECTED', 'LOCKED'],
};
export const AUGUSTUS_STATES = Object.freeze(Object.keys(transitions));
export function transitionState(current, next) {
  if (!transitions[current]?.includes(next)) throw new Error(`Invalid Augustus transition ${current} -> ${next}`);
  return next;
}
